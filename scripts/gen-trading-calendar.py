#!/usr/bin/env python3
"""Generate the trading_calendar seed for migration 0003.

The calendar is seeded data rather than runtime logic (D-15): N-3 and the derived trading day
both need a calendar that tests can rely on and that cannot shift under them. But 1800 hand-
typed rows are unauditable, so they are generated from the rules below and this script stays
in the repository as the audit trail.

Rules implemented, from NYSE practice:

  closed   New Year's Day, Martin Luther King Jr Day, Washington's Birthday, Good Friday,
           Memorial Day, Juneteenth, Independence Day, Labor Day, Thanksgiving, Christmas
  observed a holiday on Saturday moves to the Friday before, on Sunday to the Monday after
  except   when 1 January falls on a Saturday the exchange does NOT close the preceding
           31 December
  early    the Friday after Thanksgiving; 24 December when it is a session; 3 July when it is
           a session and 4 July falls on a weekday

Usage:  python3 scripts/gen-trading-calendar.py 2026 2030 > /tmp/seed.sql
"""

import sys
from datetime import date, timedelta


def easter(year: int) -> date:
    """Anonymous Gregorian algorithm."""
    a, b, c = year % 19, year // 100, year % 100
    d, e = b // 4, b % 4
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = c // 4, c % 4
    l = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l) // 451
    month = (h + l - 7 * m + 114) // 31
    day = ((h + l - 7 * m + 114) % 31) + 1
    return date(year, month, day)


def nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    """n-th weekday of a month; weekday 0 = Monday."""
    d = date(year, month, 1)
    d += timedelta(days=(weekday - d.weekday()) % 7)
    return d + timedelta(weeks=n - 1)


def last_weekday(year: int, month: int, weekday: int) -> date:
    d = date(year, month, 1) + timedelta(days=31)
    d = d.replace(day=1) - timedelta(days=1)
    while d.weekday() != weekday:
        d -= timedelta(days=1)
    return d


def observed(d: date) -> date | None:
    """Saturday moves back to Friday, Sunday forward to Monday."""
    if d.weekday() == 5:
        return d - timedelta(days=1)
    if d.weekday() == 6:
        return d + timedelta(days=1)
    return d


def holidays(year: int) -> dict[date, str]:
    out: dict[date, str] = {}

    def add(d: date | None, name: str) -> None:
        if d is not None:
            out[d] = name

    # The exception: 1 January on a Saturday does not close 31 December of the year before.
    jan1 = date(year, 1, 1)
    if jan1.weekday() == 5:
        pass                                     # no closure at all for this New Year
    else:
        add(observed(jan1), "New Year's Day")

    add(nth_weekday(year, 1, 0, 3), "Martin Luther King Jr Day")
    add(nth_weekday(year, 2, 0, 3), "Washington's Birthday")
    add(easter(year) - timedelta(days=2), "Good Friday")
    add(last_weekday(year, 5, 0), "Memorial Day")
    add(observed(date(year, 6, 19)), "Juneteenth")
    add(observed(date(year, 7, 4)), "Independence Day")
    add(nth_weekday(year, 9, 0, 1), "Labor Day")
    add(nth_weekday(year, 11, 3, 4), "Thanksgiving")
    add(observed(date(year, 12, 25)), "Christmas")
    return out


def early_closes(year: int, closed: dict[date, str]) -> dict[date, str]:
    out: dict[date, str] = {}

    def session(d: date) -> bool:
        return d.weekday() < 5 and d not in closed

    friday_after = nth_weekday(year, 11, 3, 4) + timedelta(days=1)
    if session(friday_after):
        out[friday_after] = "day after Thanksgiving"

    dec24 = date(year, 12, 24)
    if session(dec24):
        out[dec24] = "Christmas Eve"

    jul3, jul4 = date(year, 7, 3), date(year, 7, 4)
    if session(jul3) and jul4.weekday() < 5:
        out[jul3] = "day before Independence Day"

    return out


def main() -> None:
    start_year, end_year = int(sys.argv[1]), int(sys.argv[2])

    closed: dict[date, str] = {}
    early: dict[date, str] = {}
    for y in range(start_year, end_year + 1):
        h = holidays(y)
        closed.update(h)
        early.update(early_closes(y, h))

    rows = []
    d = date(start_year, 1, 1)
    end = date(end_year, 12, 31)
    while d <= end:
        if d.weekday() >= 5:
            rows.append((d, False, False, "weekend"))
        elif d in closed:
            rows.append((d, False, False, closed[d]))
        elif d in early:
            rows.append((d, True, True, early[d]))
        else:
            rows.append((d, True, False, None))
        d += timedelta(days=1)

    print("-- Generated by scripts/gen-trading-calendar.py. Do not edit by hand.")
    print(f"-- Range {start_year}-01-01 to {end_year}-12-31.")
    print("INSERT INTO trading_calendar (cal_date, is_session, early_close, note) VALUES")
    out = []
    for d, is_session, early_close, note in rows:
        n = "NULL" if note is None else "'" + note.replace("'", "''") + "'"
        out.append(f"  ('{d}', {str(is_session).lower()}, {str(early_close).lower()}, {n})")
    print(",\n".join(out) + ";")


if __name__ == "__main__":
    main()
